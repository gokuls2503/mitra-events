"""Demo CRM data for development: leads in every stage, follow-ups and bookings.

Names are obviously fake ("Demo Lead 1") so nothing is mistaken for a real customer.
"""

import datetime
import random

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction
from django.utils import timezone

from apps.accounts.models import Role, User
from apps.core.choices import EventType
from apps.crm import services
from apps.crm.models import Booking, Client, FollowUp, Lead, LeadActivity

VENUES = ["Codissia Hall", "Le Méridien", "Sri Krishna Mahal", "Residence, RS Puram", "Office, Peelamedu", "Hotel Annapoorna"]


class Command(BaseCommand):
    help = "Seed demo leads, follow-ups and bookings (development only)."

    def add_arguments(self, parser):
        parser.add_argument("--reset", action="store_true", help="Delete existing CRM data first.")

    @transaction.atomic
    def handle(self, *args, reset, **options):
        if not settings.DEBUG:
            raise CommandError("seed_crm is for development only (DEBUG must be True).")
        if reset:
            FollowUp.objects.all().delete()
            Booking.objects.all().delete()
            LeadActivity.objects.all().delete()
            Lead.objects.all().delete()
            Client.objects.all().delete()
        elif Lead.objects.exists():
            self.stdout.write("CRM data already exists. Use --reset to replace it.")
            return

        rnd = random.Random(7)
        manager = User.objects.filter(role=Role.MANAGER).first()
        staff = User.objects.filter(role=Role.STAFF).first()
        owners = [u for u in (manager, staff) if u]
        today = timezone.localdate()
        now = timezone.localtime()
        types = [t for t in EventType.values if t != EventType.OTHER]
        plan = (
            [Lead.Status.NEW] * 5
            + [Lead.Status.CONTACTED] * 4
            + [Lead.Status.MEETING] * 3
            + [Lead.Status.QUOTATION_SENT] * 3
            + [Lead.Status.NEGOTIATION] * 2
            + ["CONVERT"] * 4
            + [Lead.Status.LOST] * 2
        )

        for i, target in enumerate(plan, start=1):
            event_type = rnd.choice(types)
            lead = services.create_lead(
                name=f"Demo Lead {i}",
                phone=f"+9190000{i:05d}",
                event_type=event_type,
                event_date=today + datetime.timedelta(days=rnd.randint(10, 120)),
                venue=rnd.choice(VENUES),
                guest_count=rnd.choice([50, 100, 150, 250, 400, 600]),
                budget=rnd.choice([None, 25000, 60000, 150000, 300000]),
                message="Demo enquiry generated by seed_crm.",
                source=rnd.choice(Lead.Source.values),
                assigned_to=None if target == Lead.Status.NEW and i % 2 else rnd.choice(owners) if owners else None,
            )
            received = timezone.now() - datetime.timedelta(days=rnd.randint(0, 25))
            Lead.objects.filter(pk=lead.pk).update(created_at=received)
            lead.activities.filter(kind=LeadActivity.Kind.CREATED).update(created_at=received)

            if target == "CONVERT":
                services.convert_to_booking(
                    lead,
                    user=manager,
                    title=f"Demo Lead {i} — {lead.get_event_type_display()}",
                    event_type=event_type,
                    event_date=lead.event_date,
                    venue=lead.venue,
                    guest_count=lead.guest_count,
                    agreed_amount=rnd.choice([45000, 90000, 180000, 260000]),
                    coordinator=staff if i % 2 else manager,
                )
                continue
            if target != Lead.Status.NEW:
                services.change_status(lead, target, user=manager, lost_reason="Chose another decorator (demo)" if target == Lead.Status.LOST else "")
            if lead.is_open and target != Lead.Status.NEW:
                offset = rnd.choice([-2, -1, 0, 0, 1, 3])
                due = (now + datetime.timedelta(days=offset)).replace(hour=rnd.choice([10, 12, 16, 18]), minute=0)
                FollowUp.objects.create(lead=lead, due_at=due, kind=rnd.choice(FollowUp.Kind.values), assigned_to=lead.assigned_to, notes="Demo follow-up")

        # A repeat client with a past, completed event.
        repeat = Client.objects.order_by("id").first()
        if repeat:
            past = services.create_booking(
                client=repeat, user=manager, title=f"{repeat.name} — earlier birthday", event_type=EventType.BIRTHDAY,
                event_date=today - datetime.timedelta(days=40), venue="Residence", agreed_amount=30000,
            )
            Booking.objects.filter(pk=past.pk).update(status=Booking.Status.COMPLETED)

        self.stdout.write(self.style.SUCCESS(
            f"Seeded {Lead.objects.count()} leads, {Client.objects.count()} clients, "
            f"{Booking.objects.count()} bookings, {FollowUp.objects.count()} follow-ups."
        ))
